export const catalogs = { en, de, es };
export type Locale = keyof typeof catalogs;
export type Values = Record<string, string | number | bigint>;
export type Copy = { key: CopyKey; values?: Values };
export function copy(key: CopyKey, values?: Values): Copy {
  return { key, ...(values === undefined ? {} : { values }) };
}
const numberFormats = {
  en: new Intl.NumberFormat("en"),
  de: new Intl.NumberFormat("de"),
  es: new Intl.NumberFormat("es"),
};
const signedFormats = {
  en: new Intl.NumberFormat("en", { signDisplay: "exceptZero" }),
  de: new Intl.NumberFormat("de", { signDisplay: "exceptZero" }),
  es: new Intl.NumberFormat("es", { signDisplay: "exceptZero" }),
};
export function formatNumber(locale: Locale, value: number | bigint, signed = false): string {
  return (signed ? signedFormats : numberFormats)[locale].format(value);
}
export function translate(locale: Locale, message: Copy | CopyKey, values?: Values): string {
  const key = typeof message === "string" ? message : message.key;
  const parameters = typeof message === "string" ? values : message.values;
  return catalogs[locale][key].replace(/\{([a-zA-Z]+)\}/g, (_, name: string) => {
    const value = parameters?.[name];
    if (value === undefined) {
      throw new Error(`Missing copy parameter: ${key}.${name}`);
    }
    return typeof value === "string" ? value : formatNumber(locale, value);
  });
}
